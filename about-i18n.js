// Global Switcher
window.switchAboutLanguage = function (lang) {
  if (!window.ABOUT_I18N || !window.ABOUT_I18N[lang]) {
    lang = 'en'; // English is strictly default
  }

  try {
    localStorage.setItem('turbo_about_lang', lang);
  } catch (e) { }

  const select = document.getElementById('aboutLangSelect');
  if (select && select.value !== lang) {
    select.value = lang;
  }

  const t = window.ABOUT_I18N[lang];
  if (!t) return;

  // Update Hero elements
  const badge = document.getElementById('txtAboutHeroBadge');
  if (badge) badge.textContent = t.heroBadge;
  const sub = document.getElementById('txtAboutHeroSub');
  if (sub) sub.textContent = t.heroSub;

  // Render the Dynamic Content Area
  const container = document.getElementById('aboutDynamicCards');
  if (container) {
    container.style.opacity = '0.3';
    container.innerHTML = renderAboutCardsHtml(t);
    setTimeout(() => {
      container.style.transition = 'opacity 0.2s ease-in';
      container.style.opacity = '1';
    }, 40);
  }
};

// Auto-initialize when DOM is ready
document.addEventListener('DOMContentLoaded', function () {
  const defaultLang = localStorage.getItem('turbo_about_lang') || 'en';
  window.switchAboutLanguage(defaultLang);
});

